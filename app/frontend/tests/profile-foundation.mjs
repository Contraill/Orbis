await context.route("**/api/**", async route => {
  const url = new URL(route.request().url());
  const response = await route.fetch({ url: apiTarget + url.pathname + url.search });
  await route.fulfill({ response });
});
async function api(path, method = "GET", data) {
  return page.evaluate(async ({ path, method, data }) => {
    const response = await fetch(path, { method, headers: { "Content-Type": "application/json", ...(sessionStorage.getItem("orbis.owner-session") ? { Authorization: "Bearer " + sessionStorage.getItem("orbis.owner-session") } : {}) }, ...(data === undefined ? {} : { body: JSON.stringify(data) }) });
    return { status: response.status, data: await response.json() };
  }, { path, method, data });
}
